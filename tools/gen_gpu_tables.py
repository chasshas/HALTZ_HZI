#!/usr/bin/env python3
"""Generate shared/haltz_proto/src/gpu_tables.c: the GPU's default palette and font.

The palette is defined below (docs/gpu-protocol-v1.md section 3). The font comes from
shared/haltz_proto/assets/font8x8.txt. The generated C file is committed, so firmware builds
don't need Python; run this script again after changing either source.

    python3 tools/gen_gpu_tables.py           rewrite gpu_tables.c
    python3 tools/gen_gpu_tables.py --check   exit 1 if gpu_tables.c is out of date

Standard library only (no venv needed).
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT_TXT = ROOT / "shared/haltz_proto/assets/font8x8.txt"
OUT_C = ROOT / "shared/haltz_proto/src/gpu_tables.c"

# Default palette indices 1-15 (names match HALTZ_COLOR_* in gpu.h), as 8-bit RGB.
SYSTEM_COLORS = [
    ("white", (255, 255, 255)),
    ("red", (224, 40, 40)),
    ("green", (40, 200, 64)),
    ("blue", (48, 80, 232)),
    ("yellow", (248, 224, 48)),
    ("cyan", (48, 216, 232)),
    ("magenta", (216, 64, 216)),
    ("dark grey", (88, 88, 88)),
    ("light grey", (176, 176, 176)),
    ("orange", (248, 144, 32)),
    ("brown", (144, 88, 40)),
    ("pink", (248, 152, 192)),
    ("light green", (144, 240, 128)),
    ("light blue", (128, 176, 255)),
    ("dark blue", (24, 32, 128)),
]
CUBE_LEVELS = [0, 51, 102, 153, 204, 255]  # 16 + 36*r + 6*g + b


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def palette():
    """256 (rgb888, comment) pairs."""
    entries = [((0, 0, 0), "backdrop (black, transparent in layers)")]
    entries += [(rgb, name) for name, rgb in SYSTEM_COLORS]
    for r in range(6):
        for g in range(6):
            for b in range(6):
                rgb = (CUBE_LEVELS[r], CUBE_LEVELS[g], CUBE_LEVELS[b])
                entries.append((rgb, f"cube {r}{g}{b}"))
    for i in range(24):
        v = 8 + 10 * i
        entries.append(((v, v, v), f"grey {i}"))
    assert len(entries) == 256
    return entries


HEADER_RE = re.compile(r"^0x([0-9A-Fa-f]{2})(?:\s+(.*))?$")
ROW_RE = re.compile(r"^[#.]{8}$")


def parse_font(path):
    """Return 256 glyphs (8 bytes each) and names. Raises ValueError with a line number."""
    glyphs = [[0] * 8 for _ in range(256)]
    names = [""] * 256
    seen = set()
    lines = path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        i += 1
        if line in ("", "#") or line.startswith("# "):
            continue
        m = HEADER_RE.match(line)
        if not m:
            raise ValueError(f"{path.name}:{i}: expected '0xNN name', got {line!r}")
        code = int(m.group(1), 16)
        if code in seen:
            raise ValueError(f"{path.name}:{i}: glyph 0x{code:02X} defined twice")
        seen.add(code)
        names[code] = (m.group(2) or "").strip()
        for row in range(8):
            if i >= len(lines) or not ROW_RE.match(lines[i].rstrip()):
                got = lines[i].rstrip() if i < len(lines) else "end of file"
                raise ValueError(
                    f"{path.name}:{i + 1}: glyph 0x{code:02X} row {row}: need 8 of '#'/'.', "
                    f"got {got!r}")
            bits = lines[i].rstrip()
            glyphs[code][row] = sum(0x80 >> x for x, c in enumerate(bits) if c == "#")
            i += 1
    return glyphs, names


def c_comment_name(name):
    return name.replace("*/", "* /").replace("\\", "backslash")


def render(glyphs, names):
    out = []
    w = out.append
    w("/*")
    w(" * GPU default palette and font. GENERATED by tools/gen_gpu_tables.py: don't edit,")
    w(" * change the script (palette) or assets/font8x8.txt (font) and run it again.")
    w(" */")
    w('#include "haltz/gpu.h"')
    w("")
    w("const uint16_t haltz_gpu_default_palette[HALTZ_GPU_PALETTE_SIZE] = {")
    for idx, ((r, g, b), comment) in enumerate(palette()):
        w(f"    0x{rgb565(r, g, b):04X}, /* {idx:3d}: #{r:02X}{g:02X}{b:02X} {comment} */")
    w("};")
    w("")
    w("const uint8_t haltz_gpu_default_font[HALTZ_GPU_FONT_GLYPHS][HALTZ_GPU_GLYPH_BYTES] = {")
    for code in range(256):
        data = ", ".join(f"0x{v:02X}" for v in glyphs[code])
        label = c_comment_name(names[code]) if names[code] else "blank"
        w(f"    {{{data}}}, /* 0x{code:02X} {label} */")
    w("};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only check that the file is current")
    args = ap.parse_args()
    try:
        glyphs, names = parse_font(FONT_TXT)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    text = render(glyphs, names)
    if args.check:
        current = OUT_C.read_text(encoding="utf-8") if OUT_C.exists() else ""
        if current != text:
            print(f"{OUT_C.relative_to(ROOT)} is out of date: run tools/gen_gpu_tables.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT_C.relative_to(ROOT)} is up to date")
        return 0
    OUT_C.write_text(text, encoding="utf-8")
    print(f"wrote {OUT_C.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
