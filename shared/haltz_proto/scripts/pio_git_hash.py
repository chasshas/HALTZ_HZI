# PlatformIO pre-build script (extra_scripts = pre:...): writes haltz_git_hash.h into the
# project's source folder before every build, with the first 8 hex chars of the git commit,
# or "00000000" when git or the repository isn't available.
#
# The file is only rewritten when the hash changes, so builds stay incremental. It is
# generated: haltz_git_hash.h is listed in the repo's .gitignore.
#
# Why not CMake: PlatformIO only re-runs CMake configure when a few fixed files change, so a
# configure-time hash would go stale after every commit.
import os
import re
import subprocess

Import("env")  # noqa: F821  (provided by SCons)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
src_dir = env.subst("$PROJECT_SRC_DIR")  # noqa: F821

git_hash = "00000000"
try:
    out = subprocess.run(
        ["git", "-C", project_dir, "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        timeout=10,
    )
    if out.returncode == 0 and re.fullmatch(r"[0-9a-f]{8,}", out.stdout.strip()):
        git_hash = out.stdout.strip()[:8]
except (OSError, subprocess.SubprocessError):
    pass

content = (
    "/* Generated by shared/haltz_proto/scripts/pio_git_hash.py. Do not edit or commit. */\n"
    "#ifndef HALTZ_GIT_HASH_H\n"
    "#define HALTZ_GIT_HASH_H\n"
    '#define HALTZ_GIT_HASH "%s"\n'
    "#endif\n" % git_hash
)

header = os.path.join(src_dir, "haltz_git_hash.h")
try:
    with open(header, "r", encoding="utf-8") as f:
        old = f.read()
except OSError:
    old = None
if old != content:
    with open(header, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
print("HALTZ git hash: %s" % git_hash)
